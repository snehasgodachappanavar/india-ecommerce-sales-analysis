-- 1. DATABASE OVERVIEW AND DATA QUALITY CHECKS


SELECT COUNT(*) AS TOTAL_ROWS
FROM LIST_OF_ORDERS;

-- 2. OVERALL BUSINESS KPIs

SELECT
    SUM(AMOUNT) AS TOTAL_SALES,
    SUM(PROFIT) AS TOTAL_PROFIT,
    SUM(QUANTITY) AS TOTAL_QUANTITY_SOLD,
    COUNT(DISTINCT ORDER_ID) AS TOTAL_ORDERS,
    ROUND(SUM(AMOUNT) / COUNT(DISTINCT ORDER_ID), 2) AS AVERAGE_ORDER_VALUE,
    ROUND(SUM(PROFIT) / SUM(AMOUNT) * 100, 2) AS PROFIT_MARGIN
FROM ORDER_DETAILS;

-- 3. CATEGORY AND SUB-CATEGORY ANALYSIS

-- Sales, profit, and margin by category
SELECT
    CATEGORY,
    SUM(AMOUNT) AS TOTAL_SALES,
    SUM(PROFIT) AS TOTAL_PROFIT,
    ROUND(SUM(PROFIT) / SUM(AMOUNT) * 100, 2) AS PROFIT_MARGIN
FROM ORDER_DETAILS
GROUP BY CATEGORY
ORDER BY TOTAL_SALES DESC;


-- Top 5 sub-categories by profit
SELECT
    SUB_CATEGORY,
    SUM(AMOUNT) AS TOTAL_SALES,
    SUM(PROFIT) AS TOTAL_PROFIT,
    ROUND(SUM(PROFIT) / SUM(AMOUNT) * 100, 2) AS PROFIT_MARGIN
FROM ORDER_DETAILS
GROUP BY SUB_CATEGORY
ORDER BY TOTAL_PROFIT DESC
LIMIT 5;

-- 4. REGIONAL SALES AND PROFITABILITY

-- Sales and profit by state
SELECT
    LOO.STATE,
    SUM(OD.AMOUNT) AS TOTAL_SALES,
    SUM(OD.PROFIT) AS TOTAL_PROFIT,
    ROUND(SUM(OD.PROFIT) / SUM(OD.AMOUNT) * 100, 2) AS PROFIT_MARGIN
FROM LIST_OF_ORDERS LOO
INNER JOIN ORDER_DETAILS OD
    ON LOO.ORDER_ID = OD.ORDER_ID
GROUP BY LOO.STATE
ORDER BY TOTAL_SALES DESC;


-- Top 5 cities by sales
SELECT
    LOO.CITY,
    SUM(OD.AMOUNT) AS TOTAL_SALES,
    SUM(OD.PROFIT) AS TOTAL_PROFIT
FROM LIST_OF_ORDERS LOO
INNER JOIN ORDER_DETAILS OD
    ON LOO.ORDER_ID = OD.ORDER_ID
GROUP BY LOO.CITY
ORDER BY TOTAL_SALES DESC
LIMIT 5;

-- 5. MONTHLY SALES AND PROFIT TRENDS

SELECT
    DATE_FORMAT(
        STR_TO_DATE(LOO.ORDER_DATE, '%d-%m-%Y'),
        '%b-%y'
    ) AS MONTH_YEAR,
    SUM(OD.AMOUNT) AS TOTAL_SALES,
    SUM(OD.PROFIT) AS TOTAL_PROFIT,
    ROUND(
        SUM(OD.PROFIT) / SUM(OD.AMOUNT) * 100,
        2
    ) AS PROFIT_MARGIN
FROM LIST_OF_ORDERS LOO
INNER JOIN ORDER_DETAILS OD
    ON LOO.ORDER_ID = OD.ORDER_ID
GROUP BY
    YEAR(STR_TO_DATE(LOO.ORDER_DATE, '%d-%m-%Y')),
    MONTH(STR_TO_DATE(LOO.ORDER_DATE, '%d-%m-%Y')),
    MONTH_YEAR
ORDER BY
    YEAR(STR_TO_DATE(LOO.ORDER_DATE, '%d-%m-%Y')),
    MONTH(STR_TO_DATE(LOO.ORDER_DATE, '%d-%m-%Y'));
    
    
    -- 6. CUSTOMER ANALYSIS

