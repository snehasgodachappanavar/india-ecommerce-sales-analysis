-- 7. SALES TARGET ANALYSIS

-- Actual sales vs target by month and category
SELECT
    ACTUAL.MONTH_YEAR,
    ACTUAL.CATEGORY,
    ACTUAL.TOTAL_SALES,
    ST.TARGET,
    ROUND(ACTUAL.TOTAL_SALES / ST.TARGET * 100, 2)
        AS TARGET_ACHIEVEMENT,
    ACTUAL.TOTAL_SALES - ST.TARGET AS TARGET_GAP,
    CASE
        WHEN ACTUAL.TOTAL_SALES >= ST.TARGET
            THEN 'ACHIEVED TARGET'
        ELSE 'MISSED TARGET'
    END AS TARGET_STATUS
FROM (
    SELECT
        DATE_FORMAT(
            STR_TO_DATE(LOO.ORDER_DATE, '%d-%m-%Y'),
            '%b-%y'
        ) AS MONTH_YEAR,
        OD.CATEGORY,
        SUM(OD.AMOUNT) AS TOTAL_SALES
    FROM LIST_OF_ORDERS LOO
    INNER JOIN ORDER_DETAILS OD
        ON LOO.ORDER_ID = OD.ORDER_ID
    GROUP BY MONTH_YEAR, OD.CATEGORY
) AS ACTUAL
INNER JOIN SALES_TARGET ST
    ON ACTUAL.MONTH_YEAR = ST.MONTH_OF_ORDER_DATE
    AND ACTUAL.CATEGORY = ST.CATEGORY
ORDER BY TARGET_GAP ASC;

-- 8. ADVANCED BUSINESS INSIGHTS

-- Lowest profit-margin sub-categories
SELECT
    SUB_CATEGORY,
    SUM(AMOUNT) AS TOTAL_SALES,
    SUM(PROFIT) AS TOTAL_PROFIT,
    ROUND(SUM(PROFIT) / SUM(AMOUNT) * 100, 2) AS PROFIT_MARGIN
FROM ORDER_DETAILS
GROUP BY SUB_CATEGORY
ORDER BY PROFIT_MARGIN ASC
LIMIT 5;


-- Sub-categories generating an overall loss
SELECT
    SUB_CATEGORY,
    SUM(AMOUNT) AS TOTAL_SALES,
    SUM(PROFIT) AS TOTAL_PROFIT
FROM ORDER_DETAILS
GROUP BY SUB_CATEGORY
HAVING SUM(PROFIT) < 0
ORDER BY TOTAL_PROFIT ASC;


